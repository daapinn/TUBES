    private void BtnPayMouseClicked(java.awt.event.MouseEvent evt) {//GEN-FIRST:event_BtnPayMouseClicked
        if (NameTXT.getText().isEmpty() || Address.getText().isEmpty() || PhoneTXT.getText().isEmpty() || SubtotalTXT.getText().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Please fill in all required fields.", "Validation Error", JOptionPane.ERROR_MESSAGE);
        return;
    }

    // Check which radio button is selected and show corresponding message
    if (qris.isSelected()) {
        JOptionPane.showMessageDialog(this, "Payment with QRIS successful!", "Payment Complete", JOptionPane.INFORMATION_MESSAGE);
    } else if (bca.isSelected()) {
        JOptionPane.showMessageDialog(this, "Payment with BCA successful!", "Payment Complete", JOptionPane.INFORMATION_MESSAGE);
    } else if (dana.isSelected()) {
        JOptionPane.showMessageDialog(this, "Payment with DANA successful!", "Payment Complete", JOptionPane.INFORMATION_MESSAGE);
    } else {
        JOptionPane.showMessageDialog(this, "Please select a payment method.", "Payment Method", JOptionPane.WARNING_MESSAGE);
        return;
    }
     String paymentID = generatePaymentID();

        try {
            Connection connection = Koneksi.getKoneksi();
            String sql = "INSERT INTO payment_table (paymentid, id, name, phone, address, subtotal) VALUES (?, ?, ?, ?, ?, ?)";
            PreparedStatement statement = connection.prepareStatement(sql);
            statement.setString(1, paymentID);
            statement.setInt(2, userID);
            statement.setString(3, NameTXT.getText());
            statement.setString(4, PhoneTXT.getText());
            statement.setString(5, Address.getText());
            statement.setDouble(6, Double.parseDouble(SubtotalTXT.getText()));

            int rowsAffected = statement.executeUpdate();

            if (rowsAffected > 0) {
            JOptionPane.showMessageDialog(this, "Payment successful! PaymentID: " + paymentID, "Payment Complete", JOptionPane.INFORMATION_MESSAGE);
            this.dispose();
            thanks tx = new thanks();
            tx.setVisible(true);
            // Clear the cart after successful payment
            if (cartInstance != null) {
                cartInstance.deleteAllCartItems();
            } else {
                System.out.println("Cart instance is not initialized."); // Handle this case accordingly
            }
        } else {
            JOptionPane.showMessageDialog(this, "Failed to complete payment.", "Error", JOptionPane.ERROR_MESSAGE);
        }
    } catch (SQLException e) {
        e.printStackTrace();
        JOptionPane.showMessageDialog(this, "Error saving payment details.", "Error", JOptionPane.ERROR_MESSAGE);
    }


    }//GEN-LAST:event_BtnPayMouseClicked


private String getLastPaymentID() {
        String lastPaymentID = null;
        try {
            Connection connection = Koneksi.getKoneksi();
            String sql = "SELECT paymentid FROM payment_table ORDER BY paymentid DESC LIMIT 1";
            PreparedStatement statement = connection.prepareStatement(sql);
            ResultSet resultSet = statement.executeQuery();

            if (resultSet.next()) {
                lastPaymentID = resultSet.getString("paymentid");
            }
            resultSet.close();
            statement.close();
        } catch (SQLException e) {
            e.printStackTrace();
        }
        return lastPaymentID;
    }
      private String generatePaymentID() {
        // In this method, you can use a combination of a static prefix and an auto-incremented value.
        // For example, you can use the "JRN" prefix and auto-increment the payment ID.
        // You need to fetch the latest payment ID from the database and then increment it to generate the new one.

        // Assuming you have a method to fetch the last payment ID from the database, let's call it "getLastPaymentID()"
        String lastPaymentID = getLastPaymentID(); // Implement this method to fetch the last payment ID from the database

        // Parse the numeric part of the last payment ID and increment it by 1
        int numericPart = 1; // Default value if no last payment ID is found
        if (lastPaymentID != null && !lastPaymentID.isEmpty()) {
            numericPart = Integer.parseInt(lastPaymentID.substring(3)); // Assuming the numeric part starts from the 4th character
            numericPart++; // Increment the numeric part
        }

        // Combine the prefix and the new numeric part to form the new payment ID
        String newPaymentID = "JRN" + String.format("%03d", numericPart);

        return newPaymentID;
    
}

